export function createBlankPreventiveAudit(hotelName: string, hotelType = 'Boutique Hotel (Luxury / Historic)'): Preventive360Audit {
  const cloned = JSON.parse(JSON.stringify(INITIAL_PREVENTIVE_AUDIT_FASANO)) as Preventive360Audit;
  cloned.id = 'audit_' + Date.now();
  cloned.hotelName = hotelName;
  cloned.hotelType = hotelType;
  cloned.auditDate = new Date().toISOString().slice(0, 10);
  cloned.auditorName = 'Consulente ETRA Solutions';
  cloned.executiveNotes = 'Nuovo audit preventivo 360° avviato per ' + hotelName + '.';
  
  // Set all items to not evaluated / da migliorare as default for a blank audit
  cloned.areas.forEach(a => {
    a.items.forEach(item => {
      item.unitOrValue = 'In Rilevazione';
      item.status = 'da_migliorare';
      item.statusLabel = 'Da Valutare';
    });
  });

  return cloned;
}
